@router.post("/query/execute")
def execute_sql(payload: SQLExecuteRequest):
    try:
        cleaned_sql = normalize_sql_output(payload.sql)

        ok, message = is_safe_select_sql(cleaned_sql)
        if not ok:
            raise HTTPException(
                status_code=400,
                detail={
                    "error": "Invalid SQL",
                    "raw_sql": payload.sql,
                    "cleaned_sql": cleaned_sql,
                    "validation_message": message,
                    "source": "manual_execute",
                },
            )

        engine = get_engine(payload.connection_uri)
        result = run_select_query(engine, cleaned_sql)
        chart_suggestion = suggest_chart(result)

        return {
            "ok": True,
            "sql": cleaned_sql,
            "result": result,
            "chart_suggestion": chart_suggestion,
        }

    except HTTPException:
        raise
    except Exception as e:
        raise HTTPException(
            status_code=500,
            detail={
                "error_type": type(e).__name__,
                "error_message": str(e),
            },
        )


@router.post("/query/generate")
def generate_query(payload: PromptRunRequest):
    try:
        engine = get_engine(payload.connection_uri)

        sql, schema, source = generate_sql_from_prompt(
            engine,
            payload.prompt,
            model="llama3:8b",
        )

        if not sql or not sql.strip():
            raise HTTPException(
                status_code=400,
                detail="No SQL generated by LLM or fallback",
            )

        cleaned_sql = normalize_sql_output(sql)
        ok, message = is_safe_select_sql(cleaned_sql)

        if not ok:
            repaired_sql = None

            if source == "llm":
                try:
                    repaired_sql = repair_sql_with_llm(
                        user_prompt=payload.prompt,
                        bad_sql=cleaned_sql,
                        validation_message=message,
                        model="llama3:8b",
                    )

                    repaired_ok, repaired_message = is_safe_select_sql(repaired_sql)
                    if repaired_ok:
                        cleaned_sql = repaired_sql
                        source = "llm_repaired"
                        ok = True
                        message = repaired_message
                except Exception:
                    pass

            if not ok:
                fallback_sql = get_manual_sql_fallback(payload.prompt)
                if fallback_sql:
                    cleaned_sql = normalize_sql_output(fallback_sql)
                    fallback_ok, fallback_message = is_safe_select_sql(cleaned_sql)

                    if fallback_ok:
                        return {
                            "ok": True,
                            "prompt": payload.prompt,
                            "sql": cleaned_sql,
                            "sql_source": "manual_fallback_after_invalid_llm",
                            "schema_used": schema,
                        }

                raise HTTPException(
                    status_code=400,
                    detail={
                        "error": "Invalid SQL generated",
                        "raw_sql": sql,
                        "cleaned_sql": cleaned_sql,
                        "validation_message": message,
                        "source": source,
                    },
                )

        return {
            "ok": True,
            "prompt": payload.prompt,
            "sql": cleaned_sql,
            "sql_source": source,
            "schema_used": schema,
        }

    except HTTPException:
        raise
    except Exception as e:
        raise HTTPException(
            status_code=500,
            detail={
                "error_type": type(e).__name__,
                "error_message": str(e),
            },
        )


@router.post("/query/run")
def run_prompt_query(payload: PromptRunRequest):
    try:
        print("\n==============================")
        print("NEW REQUEST")
        print("Prompt:", payload.prompt)

        engine = get_engine(payload.connection_uri)

        sql, schema, source = generate_sql_from_prompt(
            engine,
            payload.prompt,
            model="llama3:8b",
        )

        print("\nSQL SOURCE:")
        print(source)

        print("\nRAW SQL OUTPUT:")
        print(repr(sql))

        if not sql or not sql.strip():
            raise HTTPException(
                status_code=400,
                detail="No SQL generated by LLM or fallback",
            )

        cleaned_sql = normalize_sql_output(sql)

        print("\nCLEANED SQL:")
        print(repr(cleaned_sql))

        ok, message = is_safe_select_sql(cleaned_sql)
        print("\nVALIDATION RESULT:", ok, "|", message)

        if not ok:
            repaired_sql = None

            if source == "llm":
                try:
                    print("\nTRYING LLM SQL REPAIR...")
                    repaired_sql = repair_sql_with_llm(
                        user_prompt=payload.prompt,
                        bad_sql=cleaned_sql,
                        validation_message=message,
                        model="llama3:8b",
                    )

                    print("\nREPAIRED SQL:")
                    print(repr(repaired_sql))

                    repaired_ok, repaired_message = is_safe_select_sql(repaired_sql)
                    print("\nREPAIRED VALIDATION:", repaired_ok, "|", repaired_message)

                    if repaired_ok:
                        cleaned_sql = repaired_sql
                        source = "llm_repaired"
                        ok = True
                        message = repaired_message

                except Exception as repair_error:
                    print("\nSQL REPAIR FAILED:", str(repair_error))

            if not ok and source.startswith("llm"):
                fallback_sql = get_manual_sql_fallback(payload.prompt)
                if fallback_sql:
                    print("\nTRYING MANUAL FALLBACK AFTER INVALID LLM SQL")

                    cleaned_sql = normalize_sql_output(fallback_sql)
                    fallback_ok, fallback_message = is_safe_select_sql(cleaned_sql)

                    print("\nFALLBACK VALIDATION:", fallback_ok, "|", fallback_message)

                    if fallback_ok:
                        result = run_select_query(engine, cleaned_sql)
                        chart_suggestion = suggest_chart(result)
                        explanation = generate_text_response_and_insights(
                            user_prompt=payload.prompt,
                            sql=cleaned_sql,
                            result=result,
                            model="llama3:8b",
                        )

                        print("\nRESULT ROW COUNT:", result["row_count"])
                        print("==============================\n")

                        return {
                            "ok": True,
                            "prompt": payload.prompt,
                            "sql": cleaned_sql,
                            "sql_source": "manual_fallback_after_invalid_llm",
                            "schema_used": schema,
                            "result": result,
                            "text_response": explanation["text_response"],
                            "insights": explanation["insights"],
                            "chart_suggestion": chart_suggestion,
                        }

            if not ok:
                raise HTTPException(
                    status_code=400,
                    detail={
                        "error": "Invalid SQL generated",
                        "raw_sql": sql,
                        "cleaned_sql": cleaned_sql,
                        "validation_message": message,
                        "source": source,
                    },
                )

        result = run_select_query(engine, cleaned_sql)
        chart_suggestion = suggest_chart(result)
        explanation = generate_text_response_and_insights(
            user_prompt=payload.prompt,
            sql=cleaned_sql,
            result=result,
            model="llama3:8b",
        )

        print("\nRESULT ROW COUNT:", result["row_count"])
        print("==============================\n")

        return {
            "ok": True,
            "prompt": payload.prompt,
            "sql": cleaned_sql,
            "sql_source": source,
            "schema_used": schema,
            "result": result,
            "text_response": explanation["text_response"],
            "insights": explanation["insights"],
            "chart_suggestion": chart_suggestion,
        }

    except HTTPException:
        raise
    except Exception as e:
        import traceback

        print("\nUNHANDLED ERROR:")
        print(str(e))
        traceback.print_exc()

        raise HTTPException(
            status_code=500,
            detail={
                "error_type": type(e).__name__,
                "error_message": str(e),
            },
        )